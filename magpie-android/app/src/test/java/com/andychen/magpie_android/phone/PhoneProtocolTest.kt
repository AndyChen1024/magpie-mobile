package com.andychen.magpie_android.phone

import kotlinx.coroutines.runBlocking
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class PhoneProtocolTest {
    @Test
    fun revokedProfileReopensForScanningWithoutContactingTheOldRelay() = runBlocking {
        val offer = PhonePairing.parse(link()).offer
        val identity = PhoneIdentity.generate()
        val legacy = PhoneProfile.fromStoredMetadata(offer.json, identity)
        var reconnectedDevice: String? = null
        restorePhoneConnection(legacy, { error("An existing grant should reconnect") }, {
            reconnectedDevice = it.identity.deviceId
        })
        assertEquals(identity.deviceId, reconnectedDevice)

        var stored = offer.json.toString()
        val rejected = recordPhoneRevocation(legacy) {
            assertEquals(identity.deviceId, it.identity.deviceId)
            stored = it.storedMetadata().toString()
        }
        assertTrue(rejected.canScan)
        val restored = PhoneProfile.fromStoredMetadata(parseObject(stored), identity)
        var status: PhoneStatus? = null
        restorePhoneConnection(restored, { status = it }, { error("The old relay is offline") })
        assertEquals(PhoneStatus.AuthorizationLost, status)
        assertTrue(PhoneConnectionState(status = requireNotNull(status)).canScan)
        assertEquals(identity.deviceId, restored.identity.deviceId)
    }

    @Test
    fun signaturesMatchMacReferenceIncludingAuthTrailingLf() {
        // Public test vector generated by Node's Ed25519 and the plugin's proofBytes.
        val identity = PhoneIdentity.fromSeed(ByteArray(32) { 0x42 })
        val nonce = base64Url(ByteArray(32) { 0x21 })
        val ticket = base64Url(ByteArray(32) { 0x57 })
        assertEquals("IVL40Zt5HSRFMkLhXy6rbLfP-ntqXtMAl5YOBpiB2xI", identity.publicKey)
        assertEquals("MJfi3uLLSjS1OEDNtwWu1xBnw29o2w4PVZw_P6BDMV8", identity.deviceId)
        assertEquals(
            "8N4L1atDdgTbK2bk_zJxvfoWyyvAbF45SW2oeGSLk2m_XNU_8Q3Yw8x3vMe6TVAVHbXrt7xC6Iqtlk6drznVBw",
            identity.proof("fixture-mac", nonce, "device.pair", ticket),
        )
        assertEquals(
            "adHFyPVoOM4Va1No5mhc078963ZZW5BKAoftEPA08HOqanR-iFRV17tAvclb8pM8Qe2JGGvyUzK5GtO_wcgGCQ",
            identity.proof("fixture-mac", nonce, "device.auth"),
        )
    }

    @Test
    fun offerPinsProtectedAndBuildsTheV2ClientRoute() {
        val pairing = PhonePairing.parse(link())
        assertEquals("http://127.0.0.1:18400/ws?serverId=fixture-mac&role=client&v=2", pairing.offer.relayUrl.toString())
        assertFalse("ticket" in pairing.offer.json)
        assertEquals(
            "https://relay.example/ws?serverId=fixture-mac&role=client&v=2",
            PhonePairing.parse(link(endpoint = "relay.example:443", tls = true)).offer.relayUrl.toString(),
        )
        assertThrows(Exception::class.java) { PhonePairing.parse(link() + "&ticket=$ticket") }
        assertThrows(Exception::class.java) { PhonePairing.parse(link() + "=") }
        assertThrows(Exception::class.java) { PhonePairing.parse(link(mode = "legacy")) }
        assertThrows(Exception::class.java) { PhonePairing.parse(link(endpoint = "relay.example:8080")) }
    }

    @Test
    fun receiptMustMatchTheRequestAndPairedHost() {
        val receipt = "848354b0-491e-4972-99d3-f1941032d072"
        val response = reply(receipt)
        assertEquals(receipt, HostReading.fromReply(response, "read-1", "fixture-mac").receipt)
        assertThrows(Exception::class.java) { HostReading.fromReply(response, "read-2", "fixture-mac") }
        assertThrows(Exception::class.java) { HostReading.fromReply(response, "read-1", "different-mac") }
        assertThrows(Exception::class.java) { HostReading.fromReply(reply(""), "read-1", "fixture-mac") }
    }

    private val ticket = base64Url(ByteArray(32) { 0x57 })

    private fun link(endpoint: String = "127.0.0.1:18400", tls: Boolean = false, mode: String = "protected"): String {
        val offer = buildJsonObject {
            put("v", 2)
            put("serverId", "fixture-mac")
            put("minimumSecurityMode", mode)
            put("daemonPublicKeyB64", standardBase64(ByteArray(32) { 0x14 }))
            put("relay", buildJsonObject {
                put("endpoint", endpoint)
                put("useTls", tls)
            })
            put("ticket", "unknown offer property")
        }
        return "magpie-mobile://pair#offer=${base64Url(offer.toString().encodeToByteArray())}&ticket=$ticket"
    }

    private fun reply(receipt: String) = buildJsonObject {
        put("id", "read-1")
        put("hostId", "fixture-mac")
        put("displayName", "Fixture Mac")
        put("receipt", receipt)
    }
}
